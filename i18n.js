const LANGS = { en: 'English', ms: 'Bahasa Melayu', zh: '中文' };
const LANG_INDEX = { ms: 0, zh: 1 };
const I18N_ATTRS = ['placeholder', 'aria-label', 'title'];

const I18N_LOWER = {};
Object.keys(I18N).forEach((k) => (I18N_LOWER[k.toLowerCase()] = k));

let currentLang = 'en';

const isUpper = (s) => /[A-Z]/.test(s) && s === s.toUpperCase();

// Cari terjemahan satu frasa (tanpa ruang di hujung); null jika tiada
function lookup(text) {
  const i = LANG_INDEX[currentLang];
  if (text in I18N) return I18N[text][i];
  const key = I18N_LOWER[text.toLowerCase()];
  if (key) {
    const out = I18N[key][i];
    return isUpper(text) && currentLang === 'ms' ? out.toUpperCase() : out;
  }
  for (const [re, fn] of I18N_PATTERNS) {
    const m = text.match(re);
    if (m) {
      const out = fn(m, currentLang);
      if (out != null) return out;
    }
  }
  // Frasa bercantum "A · B" / "A // B" / "A — B": terjemah setiap bahagian
  for (const sep of [' · ', ' // ', ' — ']) {
    if (text.includes(sep)) {
      let changed = false;
      const parts = text.split(sep).map((p) => {
        const t = lookup(p);
        if (t != null) changed = true;
        return t ?? p;
      });
      if (changed) return parts.join(sep);
    }
  }
  return null;
}

