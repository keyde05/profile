// ---------- Penukaran DOM
const textState = new WeakMap(); // nod teks → { orig, out }
const attrState = new WeakMap(); // elemen → { [attr]: { orig, out } }

const skip = (el) => !el || el.closest('script, style, [data-no-i18n]');

function translateString(orig) {
  if (currentLang === 'en') return orig;
  const m = orig.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const core = m[2].replace(/\s+/g, ' ');
  if (!core || !/[A-Za-z]/.test(core)) return orig;
  const t = lookup(core);
  return t == null ? orig : m[1] + t + m[3];
}

function processText(node) {
  if (skip(node.parentElement)) return;
  const st = textState.get(node);
  const current = node.nodeValue;
  const orig = st && current === st.out ? st.orig : current;
  const out = translateString(orig);
  if (out !== current) node.nodeValue = out;
  textState.set(node, { orig, out });
}

function processAttrs(el) {
  if (skip(el)) return;
  let st = attrState.get(el);
  for (const a of I18N_ATTRS) {
    const current = el.getAttribute(a);
    if (current == null) continue;
    if (!st) attrState.set(el, (st = {}));
    const prev = st[a];
    const orig = prev && current === prev.out ? prev.orig : current;
    const out = translateString(orig);
    if (out !== current) el.setAttribute(a, out);
    st[a] = { orig, out };
  }
}

function processTree(root) {
  if (root.nodeType === Node.TEXT_NODE) return processText(root);
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  processAttrs(root);
  root.querySelectorAll('[placeholder], [aria-label], [title]').forEach(processAttrs);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = walker.nextNode())) processText(n);
}

function applyLanguage(lang) {
  currentLang = lang in LANGS ? lang : 'en';
  document.documentElement.lang = { en: 'en', ms: 'ms', zh: 'zh-Hans' }[currentLang];
  document.title = currentLang === 'en' ? 'Muhammad Shafiq Danial | Full Stack Developer'
    : currentLang === 'ms' ? 'Muhammad Shafiq Danial | Pembangun Full Stack' : 'Muhammad Shafiq Danial | 全栈开发者';
  processTree(document.body);
  $$('[data-lang-switch]').forEach((sw) => {
    sw.dataset.active = currentLang;
    $$('[data-lang]', sw).forEach((b) => b.setAttribute('aria-selected', String(b.dataset.lang === currentLang)));
    const code = $('[data-lang-code]', sw);
    if (code) code.textContent = { en: 'EN', ms: 'BM', zh: '中' }[currentLang];
  });
  try {
    localStorage.setItem('msd-lang', currentLang);
  } catch (e) {
    /* storan tidak tersedia */
  }
}

function initI18n() {
  // Terjemah kandungan baharu / berubah secara automatik
  new MutationObserver((records) => {
    if (currentLang === 'en') return;
    for (const r of records) {
      if (r.type === 'characterData') processText(r.target);
      else if (r.type === 'attributes') processAttrs(r.target);
      else r.addedNodes.forEach(processTree);
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: I18N_ATTRS });

  // Dropdown bahasa: buka/tutup menu, pilih bahasa + gelombang orbit dari titik klik
  const closeMenus = (except) =>
    $$('[data-lang-switch]').forEach((sw) => {
      if (sw === except) return;
      $('.lang-moons', sw).hidden = true;
      $('[data-lang-toggle]', sw).setAttribute('aria-expanded', 'false');
      sw.classList.remove('is-open');
    });

  document.addEventListener('click', (e) => {
    if (!e.target.closest('[data-lang-switch]')) closeMenus();
  });
  window.addEventListener(
    'keydown',
    (e) => {
      const open = $$('[data-lang-switch].is-open')[0];
      if (!open || e.key !== 'Escape') return;
      e.preventDefault();
      e.stopImmediatePropagation(); // jangan langkau skrin pembukaan / keluar dari world
      closeMenus();
      $('[data-lang-toggle]', open).focus();
    },
    true
  );

  $$('[data-lang-switch]').forEach((sw) =>
    sw.addEventListener('click', (e) => {
      const toggle = e.target.closest('[data-lang-toggle]');
      if (toggle) {
        const opening = !sw.classList.contains('is-open');
        closeMenus(sw);
        sw.classList.toggle('is-open', opening);
        $('.lang-moons', sw).hidden = !opening;
        toggle.setAttribute('aria-expanded', String(opening));
        if (opening) $('[aria-selected="true"]', sw)?.focus();
        return;
      }
      const btn = e.target.closest('[data-lang]');
      if (!btn) return;
      closeMenus();
      if (btn.dataset.lang === currentLang) return;
      // Bulan "mendarat" ke dalam planet
      sw.classList.remove('is-landing');
      void sw.offsetWidth;
      sw.classList.add('is-landing');
      setTimeout(() => sw.classList.remove('is-landing'), 700);
      const r = btn.getBoundingClientRect();
      const wave = document.createElement('div');
      wave.className = 'lang-wave';
      wave.style.setProperty('--x', `${r.left + r.width / 2}px`);
      wave.style.setProperty('--y', `${r.top + r.height / 2}px`);
      document.body.appendChild(wave);
      document.documentElement.classList.add('lang-switching');
      setTimeout(() => applyLanguage(btn.dataset.lang), 220);
      setTimeout(() => {
        document.documentElement.classList.remove('lang-switching');
        wave.remove();
      }, 900);
    })
  );

  let saved = null;
  try {
    saved = localStorage.getItem('msd-lang');
  } catch (e) {
    /* storan tidak tersedia */
  }
  const nav = (navigator.language || '').toLowerCase();
  applyLanguage(saved || (nav.startsWith('zh') ? 'zh' : nav.startsWith('ms') ? 'ms' : 'en'));
}
